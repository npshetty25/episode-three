"""The Model A data funnel report and the K = 6 diagnosis. Pure functions: documents in, text out.

Deterministic on purpose: no timestamps, sorted keys, fixed decimals, so a re-run changes nothing in git.
There are NO feature-label correlations here (spec: looking at them before the split is decided is a leak of
attention, not of data, and still not allowed).
"""
import statistics
from collections import Counter

from episode_three.features import model_a

SPLITS = ("train", "validation", "test")
FLAGS = ("marker_disagreement", "m1_unknown", "multi_episode_premiere", "label_offset_unusual",
         "fallback_w1", "fallback_w2", "binge")
STEP_ORDER = ("no_w1_records", "m3_not_before_m4", "no_ep1_4_trends", "no_ep3_snapshot",
              "ep3_popularity_low", "no_primary_label")


def split_of(document):
    return model_a.assign_split(document["season_year"])


def label_stats(scores):
    if not scores:
        return "0", "-", "-"
    sd = statistics.stdev(scores) if len(scores) > 1 else 0.0
    return str(len(scores)), f"{statistics.mean(scores):.2f}", f"{sd:.2f}"


def floor_counts(documents):
    """How many shows had a window changed by the M(n) + 1 floor, and how many lost their snapshot to it."""
    with_w1 = [d for d in documents if "no_w1_records" not in d["reasons"]]
    return {key: sum(1 for d in with_w1 if d["floor"][which][what])
            for key, (which, what) in {"ep3_window_shrunk": ("ep3", "shrunk"), "ep3_lost": ("ep3", "lost"),
                                       "ep1_window_shrunk": ("ep1", "shrunk"), "ep1_lost": ("ep1", "lost")}.items()} | {
        "shows_with_w1": len(with_w1)}


def funnel_markdown(all_candidates, documents):
    """The funnel as Markdown. all_candidates: every listed model_a_candidates doc; documents: build_all output."""
    listed = len(all_candidates)
    ineligible = [c for c in all_candidates if not c.get("eligible")]
    reasons = Counter(r for c in ineligible for r in c.get("exclusion_reasons", []))
    lines = ["# Model A data funnel", "",
             "Generated by `python -m scripts.build_model_a_features`. Deterministic: no timestamps.",
             "No feature-label correlations are shown on purpose.", "",
             "## From listed to eligible", "",
             f"- Listed by AniList (TV/ONA, Japan, non-adult, popularity >= 2,000 today): **{listed:,}**",
             f"- Not eligible: **{len(ineligible):,}** (a show can have several reasons, so the reasons add up to more):"]
    lines += [f"  - {reason}: {count:,}" for reason, count in sorted(reasons.items())]
    lines += [f"- **Eligible: {len(documents):,}**", "", "## From eligible to trainable", "",
              "Each show is counted at the first step it fails (funnel order). `Also` counts the later reasons that are also true.",
              "", "| Step | Excluded here | Remaining | Also true (later reasons) |", "|---|---:|---:|---:|"]
    remaining = len(documents)
    first = Counter(d["reasons"][0] for d in documents if d["reasons"])
    also = Counter(r for d in documents for r in d["reasons"][1:])
    for step in STEP_ORDER:
        remaining -= first[step]
        lines.append(f"| {step} | {first[step]:,} | {remaining:,} | {also[step]:,} |")
    trainable = [d for d in documents if d["status"] == "trainable"]
    assert remaining == len(trainable), "the funnel does not add up"
    lines += ["", f"**Trainable: {len(trainable):,}** of {len(documents):,} eligible.", "", "Sub-reasons:", ""]
    subs = Counter((r, s) for d in documents for r, s in d["subreasons"].items())
    lines += [f"- {reason} / {sub}: {count:,}" for (reason, sub), count in sorted(subs.items())]
    lines += ["", "## Trainable shows per split", "", "| Split | Shows | Seasons |", "|---|---:|---|"]
    by_split = {s: [d for d in trainable if split_of(d) == s] for s in SPLITS}
    for s in SPLITS:
        keys = sorted(model_a.season_key(d["season_year"], d["season"]) for d in by_split[s])
        span = (f"{model_a.SEASON_ORDER[keys[0][1]].title()} {keys[0][0]} to "
                f"{model_a.SEASON_ORDER[keys[-1][1]].title()} {keys[-1][0]}") if keys else "-"
        lines.append(f"| {s} | {len(by_split[s]):,} | {span} |")
    lines += ["", "## Flags among trainable shows (nothing is excluded for a flag)", "",
              "| Flag | " + " | ".join(SPLITS) + " | total |", "|---|" + "---:|" * (len(SPLITS) + 1)]
    for flag in FLAGS:
        counts = [sum(1 for d in by_split[s] if d["flags"][flag]) for s in SPLITS]
        lines.append(f"| {flag} | " + " | ".join(str(c) for c in counts) + f" | {sum(counts)} |")
    lines += ["", "Nulls among trainable shows:", ""]
    for name in ("ep1_score", "popularity_growth_1_3", "ep3_popularity_vs_prev_season", "prequel_finale_score"):
        lines.append(f"- {name}: {sum(1 for d in trainable if d['features'][name] is None):,}")
    lines += [f"- is_sequel true: {sum(1 for d in trainable if d['features']['is_sequel']):,}; "
              f"prequel_score_known true: {sum(1 for d in trainable if d['features']['prequel_score_known']):,}"]
    floor = floor_counts(documents)
    lines += ["", "## Floor impact (the window starts at M(prev) + 1)", "",
              f"Of the {floor['shows_with_w1']:,} eligible shows with w1 data:", "",
              f"- ep3 window narrowed by the floor: {floor['ep3_window_shrunk']:,}; lost their ep3 snapshot because of it: {floor['ep3_lost']:,}",
              f"- ep1 window narrowed by the floor: {floor['ep1_window_shrunk']:,}; lost their ep1 snapshot because of it: {floor['ep1_lost']:,} (ep1 features become null; the show is kept)"]
    lines += ["", "## Label distribution (primary label, trainable shows)", "",
              "| Split | n | mean | sd |", "|---|---:|---:|---:|"]
    for s in SPLITS:
        n, mean, sd = label_stats([d["label"]["score"] for d in by_split[s]])
        lines.append(f"| {s} | {n} | {mean} | {sd} |")
    dropped = sorted((d["_id"], d["prequel_dropped_by_date"]) for d in documents if d["prequel_dropped_by_date"])
    lines += ["", "## Prequel scores dropped by the date rule", "",
              f"{len(dropped)} shows had a prequel with a label that was not final before their ep3 snapshot.", ""]
    lines += [f"- {show}: {', '.join(prequels)}" for show, prequels in dropped]
    return "\n".join(lines) + "\n"


def diagnose_k(documents, w1_by_id, k=6):
    """Shows without an ep3 snapshot under K = 3: how many would get one with a floored K = 6 window?

    Nothing is applied. Returns counts and the rescued shows' ep3 popularity.
    """
    missing = [d for d in documents if d["reasons"] and d["reasons"][0] == "no_ep3_snapshot"]
    rescued = []
    for d in missing:
        m3, m4 = d["markers"]["m3"]["day"], d["markers"]["m4"]["day"]
        snapshot, _ = model_a.select_snapshot(w1_by_id.get(d["_id"], []), m3, m4, k)
        if snapshot:
            rescued.append((d["_id"], snapshot["popularity"]))
    passing = [r for r in rescued if r[1] is not None and r[1] >= model_a.POPULARITY_MIN]
    return {"missing": len(missing), "rescued": rescued, "passing": passing,
            "subreasons": Counter(d["subreasons"].get("no_ep3_snapshot") for d in missing)}
